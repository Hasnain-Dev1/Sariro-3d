/** A cell that will not collapse in Outlook. */
const spacer = (h) =>
  `<tr><td height="${h}" style="height:${h}px;font-size:0;line-height:0;">&nbsp;</td></tr>`;

/**
 * The tactile ledge: `box-shadow: 0 Npx 0` rebuilt as a table row, so it lands
 * in Outlook. Inset each side so it reads as the underside of the thing above
 * rather than as a second object.
 */
const ledge = (color, { height = 6, inset = 5, radius = 10 } = {}) => `
                <tr>
                  <td style="font-size:0;line-height:0;">
                    <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%">
                      <tr>
                        <td width="${inset}" style="width:${inset}px;font-size:0;line-height:0;">&nbsp;</td>
                        <td bgcolor="${color}" height="${height}" style="background-color:${color};height:${height}px;font-size:0;line-height:0;border-radius:0 0 ${radius}px ${radius}px;">&nbsp;</td>
                        <td width="${inset}" style="width:${inset}px;font-size:0;line-height:0;">&nbsp;</td>
                      </tr>
                    </table>
                  </td>
                </tr>`;

/** The button, with its ledge. The site's primary control, in mail. */
const button = (label, href, face = C.blue, under = C.blueDark, fg = C.white) => `
              <table role="presentation" cellpadding="0" cellspacing="0" border="0" align="center" style="margin:0 auto;">
                <tr>
                  <td align="center" bgcolor="${face}" style="background-color:${face};border-radius:14px;padding:17px 38px;mso-padding-alt:17px 38px;">
                    <a href="${href}" target="_blank" style="display:inline-block;font-family:${GROTESK};font-size:16px;font-weight:700;line-height:20px;letter-spacing:0.2px;color:${fg};text-decoration:none;">${label}</a>
                  </td>
                </tr>${ledge(under, { height: 6, inset: 4, radius: 11 })}
              </table>`;

/**
 * The one-time code, as a ticket.
 *
 * A dashed edge and a torn corner, because that is what a code that works once
 * and then never again actually is. It also stops it reading as a form field
 * somebody is meant to type INTO, which a plain bordered box does.
 */
const ticket = (intro, size = 30) => `
              <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%">
                <tr>
                  <td style="padding:6px 0 10px;font-family:${BODY};font-size:13px;line-height:20px;color:${C.muted};">${intro}</td>
                </tr>
                <tr>
                  <td align="center" bgcolor="${C.panel}" style="background-color:${C.panel};border:2px dashed ${C.ledge};border-radius:14px;padding:20px 12px 18px;">
                    <div style="font-family:${MONO};font-size:${size}px;font-weight:700;letter-spacing:11px;line-height:1.1;color:${C.deep};text-indent:11px;">{{ .Token }}</div>
                  </td>
                </tr>
              </table>`;

/** Body paragraph. */
const P = (text, top = 0, bottom = 20) =>
  `              <p style="margin:${top}px 0 ${bottom}px;font-family:${BODY};font-size:16px;line-height:27px;color:${C.ink};">${text}</p>`;

/** The small print, on a warm inset with a coloured rule down its left edge. */
const smallprint = (text, accent) => `
              <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="margin-top:26px;">
                <tr>
                  <td width="4" bgcolor="${accent}" style="width:4px;background-color:${accent};font-size:0;line-height:0;border-radius:3px 0 0 3px;">&nbsp;</td>
                  <td bgcolor="${C.panel}" style="background-color:${C.panel};padding:14px 16px;border-radius:0 8px 8px 0;font-family:${BODY};font-size:13px;line-height:21px;color:${C.ink};">${text}</td>
                </tr>
              </table>`;

/** A person reads the replies. Worth saying, and nobody else says it. */
const ps = (text) => `
              <table role="presentation" cellpadding="0" cellspacing="0" border="0" width="100%" style="margin-top:26px;border-top:1px solid ${C.line};">
                <tr>
                  <td style="padding:16px 0 0;font-family:${BODY};font-style:italic;font-size:13px;line-height:21px;color:${C.muted};">${text}</td>
                </tr>
              </table>`;

