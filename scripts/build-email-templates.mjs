/**
 * SARIRO — the six emails Supabase sends on our behalf
 * ============================================================================
 * Generates supabase/email-templates/*.html. Run:  npm run email:build
 *
 * Each output file is standalone — open it, copy the whole thing, paste it into
 * Supabase → Authentication → Emails. That is the only way those templates can
 * be set, so each file has to survive being copied out of the repo with nothing
 * attached: no stylesheet, no hosted image, no font.
 *
 * ── Why a generator and not six hand-written files ──────────────────────────
 * They are 90% the same, and the 90% is the part nobody re-reads. Six copies of
 * a footer is six chances for the support address to be right in five of them.
 * The shell is written once; each template supplies a heading, a sentence and
 * a button.
 *
 * ── Making an email look like Sariro ────────────────────────────────────────
 * The site's signature is not its blue. It is DEPTH — .btn-tactile-primary is
 * `box-shadow: 0 10px 0 -1px var(--brand-blue-dark)`: a hard, purely vertical
 * ledge under every button, so things look pressable rather than printed. Warm
 * paper (#FBF9F6) instead of the usual cold grey, warm near-black (#1A1611)
 * instead of slate.
 *
 * box-shadow does not exist in Outlook, and half our parents open mail on a
 * phone where it is a coin toss. So the ledge is not a shadow here — it is a
 * TABLE ROW. A darker cell, six pixels tall, inset a few pixels, sitting under
 * the thing it belongs to. Structure instead of style, which means it renders
 * in Outlook 2013 exactly as it does in Apple Mail. That one trick is what
 * makes these look like the product instead of like a receipt.
 *
 * The rest follows the same rule — every effect is built from cells:
 *   · the five-colour brand bar across the top of the card is five <td>s
 *   · the headline sits on a warm-black band, reversed out, with the kicker in
 *     that email's accent colour — so which of the six this is reads from
 *     across the room, before a word of it does
 *   · the underline under each heading is a cell 52px wide and 5px tall
 *   · the code sits in a dashed "ticket", the way a one-time code should
 *
 * ── Why the HTML otherwise looks like it is from 2004 ───────────────────────
 * Because Outlook renders mail with Word.
 *   · every colour is inline AND on a bgcolor attribute — Gmail's mobile app
 *     strips <style> entirely
 *   · button padding is on the <td>, never on the <a>; Outlook drops padding
 *     on inline elements and the button collapses to bare underlined text
 *   · spacer cells carry &nbsp; at font-size:0, or Outlook collapses them
 *   · a linear-gradient always sits on top of a solid background-color, so
 *     Outlook shows blue rather than nothing
 *   · the logo is type, not an image. SVG does not render in Gmail at all, and
 *     a PNG that fails to load leaves a broken-image icon at the top of a
 *     security email — exactly where it costs the most trust
 *
 * ── The template variables are Supabase's ───────────────────────────────────
 * Go templates: {{ .ConfirmationURL }}, {{ .Token }}, {{ .Email }},
 * {{ .NewEmail }}. Left untouched in the output.
 *
 * Note there is no {{ slice .Token 0 1 }} anywhere, tempting as one digit per
 * tile would look. Supabase does not promise which template functions are
 * available, and an auth email that fails to render is an account nobody can
 * get into. The code goes out whole.
 */

